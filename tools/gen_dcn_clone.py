#!/usr/bin/env python3
"""
gen_dcn_clone.py - register lists for cloning a lit DCN 3.2 pipe onto a
free one (hw/dcn32_clone.c): every register amdgpu programs per instance in
HUBP, DPP, MPCC, OPP/FMT, ODM, OTG and the DIG front end, as offsets of
instance 0 plus the instance stride, minus registers with side effects
(status, interrupts, triggers, counters, CRC, locks, LUT data ports).

  tools/gen_dcn_clone.py dcn_3_2_0_offset.h > hw/gen/dcn_3_2_0_clone.h

The stride of each block is checked on instance 1 for every register.
"""
import re
import sys

BLOCKS = [
    # name, prefixes (instance digit after them), instances
    ("hubp", ["HUBP", "HUBPREQ", "HUBPRET"], 4),
    ("dpp", ["DPP_TOP", "CNVC_CFG", "CNVC_CUR", "DSCL", "CM"], 4),
    ("mpcc", ["MPCC"], 4),
    ("opp", ["FMT", "OPP_PIPE"], 4),
    ("odm", ["ODM"], 4),
    ("otg", ["OTG"], 4),
    ("digfe", ["DIG", "AFMT", "DME"], 5),
]

# side effects or state that must not be copied
DENY = re.compile(
    r"STATUS|_INT_|INTERRUPT|_ACK|CLEAR|FLIP_CONTROL|FORCE|TRIG|COUNT_NOW|_EVENT|"
    r"(?<!C)LOCK|DEBUG|TEST|CRC|SNAPSHOT|_RESET|GSL|STEREO|MANUAL|UNDERFLOW|DOUBLE_BUF|"
    r"PENDING|VUPDATE|FRAME_COUNT|POSITION|VLINE|NOM_VCOUNT|SECURITY|INDEX|_DATA$|"
    r"LUT_DATA|RAM_DATA|_RAM_|SEQ_|_MEM_PWR|BLANK_DATA|_CNTL_STATUS|"
    r"_BE_|DIG_BE|TMDS_|LVTMA|DP_|HPO|DIG_CLOCK_PATTERN|VERSION|READBACK|INUSE|LINE_VALUE"
)
# global sync values optc1_program_global_sync writes, despite DENY
ALLOW = re.compile(r"^OTG\d_OTG_VUPDATE_(PARAM|KEEPOUT)$")
# registers the clone programs explicitly (routing, enables), not copied
EXPLICIT = re.compile(
    r"^(HUBP\d_DCHUBP_CNTL|MPCC\d_MPCC_(TOP_SEL|BOT_SEL|OPP_ID)|OTG\d_OTG_(CONTROL|MASTER_EN)|"
    r"ODM\d_OPTC_DATA_SOURCE_SELECT|DIG\d_DIG_FE_CNTL|HUBPREQ\d_DCSURF_(PRIMARY|SECONDARY)"
    r"_(META_)?SURFACE_ADDRESS(_HIGH)?(_C)?)$"
)


def main():
    regs, idx = {}, {}
    for line in open(sys.argv[1]):
        m = re.match(r"#define reg(\w+)_BASE_IDX\s+(\d+)", line)
        if m:
            idx[m.group(1)] = int(m.group(2))
            continue
        m = re.match(r"#define reg(\w+)\s+(0x[0-9a-fA-F]+)", line)
        if m:
            regs[m.group(1)] = int(m.group(2), 16)
    out = ["/*", " * GENERATED by tools/gen_dcn_clone.py from dcn_3_2_0_offset.h (Linux amdgpu,",
           " * MIT, Copyright Advanced Micro Devices). Do not edit; regenerate.", " *",
           " * Per-instance registers copied from a lit pipe to a free one: offsets of",
           " * instance 0 (same segment within a block) and the instance stride.", " *",
           " * SPDX-License-Identifier: MIT", " */",
           "#ifndef DCN_3_2_0_CLONE_H", "#define DCN_3_2_0_CLONE_H", ""]
    for name, prefixes, ninst in BLOCKS:
        rows = []
        stride = seg = None
        for r in sorted(regs, key=lambda k: regs[k]):
            m = re.match(r"(%s)0_(\w+)$" % "|".join(prefixes), r)
            if not m or r not in idx:
                continue
            if (DENY.search(m.group(2)) and not ALLOW.match(r)) or EXPLICIT.match(r):
                continue
            r1 = "%s1_%s" % (m.group(1), m.group(2))
            if r1 not in regs or idx.get(r1) != idx[r]:
                continue
            s = regs[r1] - regs[r]
            if name == "otg" and idx[r] != 2:
                continue        # OTGn_* in the DCCG segment (pixel rate) are separate
            if stride is None:
                stride, seg = s, idx[r]
            if s != stride or idx[r] != seg:
                continue        # another sub-block with its own stride: skipped
            rows.append((regs[r], r))
        out.append("/* %s: %d registers, stride 0x%x, segment %d */" % (name, len(rows), stride, seg))
        out.append("#define RD_CLONE_%s_STRIDE 0x%x" % (name.upper(), stride))
        out.append("#define RD_CLONE_%s_SEG    %d" % (name.upper(), seg))
        out.append("static const uint16_t rd_clone_%s[] = {" % name)
        for off, r in rows:
            out.append("    0x%04x, /* %s */" % (off, r))
        out.append("};")
        out.append("")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
