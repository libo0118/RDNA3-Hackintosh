#!/usr/bin/env python3
"""
update_index.py - rebuild tools/progress/amdgpu-index.tsv, the list of
amdgpu functions the project tracks (the denominator of the "amdgpu" status).

    python3 tools/progress/update_index.py

Fetches every Linux file named in tools/progress/sources.txt at the pinned
tag (or the tag its line names: a file newer than the pin, such as the user
queue code), extracts its function definitions, drops what can never apply to a
macOS port (debugfs, sysfs, RAS, SR-IOV, XGMI, Linux module glue) and
writes "group<TAB>file<TAB>function" lines. Run it after adding a file to
sources.txt; commit the result (tools/progress.py works offline).
"""
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
TAG = "v6.12"
BASE = "https://raw.githubusercontent.com/torvalds/linux/{tag}/drivers/gpu/drm/amd/"

# a definition: a line starting at column 0 with a return type, the name, the
# parameter list (may span lines), then "{" on the next line
DEF = re.compile(r"^(?!return\b|else\b|if\b|for\b|while\b|switch\b|do\b)"
                 r"(?:[A-Za-z_][\w \t\*]*?[ \t\*])?"      # return type (or on the line above)
                 r"([a-z_][a-z0-9_]*)\s*\(([^;{}]*?)\)\s*\n\{", re.M)
# never meaningful for this driver
SKIP = re.compile(r"debugfs|sysfs|_show$|_store$|\bras\b|_ras_|^ras_|sriov|_vf_|xgmi|_print|_dump|"
                  r"module_|_procfs|_trace|_mca_|_aca_|_cper", re.I)


def functions(text):
    names = []
    for m in DEF.finditer(text):
        name = m.group(1)
        if name in ("if", "for", "while", "switch", "sizeof") or SKIP.search(name):
            continue
        names.append(name)
    return sorted(set(names))


def main():
    out = []
    for line in (HERE / "sources.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [x.strip() for x in line.split("|")]
        group, path = fields[0], fields[1]
        tag = fields[2] if len(fields) > 2 and fields[2] else TAG
        with urllib.request.urlopen(BASE.format(tag=tag) + path) as r:
            text = r.read().decode("utf-8", "replace")
        names = functions(text)
        print(f"{group:28} {path:55} {len(names)}", file=sys.stderr)
        out += [f"{group}\t{path}\t{n}" for n in names]
    (HERE / "amdgpu-index.tsv").write_text(
        f"# amdgpu functions tracked by the project (Linux {TAG} unless sources.txt names a tag); "
        "generated by update_index.py\n"
        + "\n".join(out) + "\n")


if __name__ == "__main__":
    main()
