#!/usr/bin/env python3
"""gen_xnu_kpi_lists.py - the x86_64 symbols a macOS kernel exports only from
com.apple.kpi.private, and only from com.apple.kpi.unsupported, from xnu's
config/*.exports (card run 2026-10-25b, DRIVER-PLAN N47).

CI's macOS runner is older than the macOS the driver also runs on, so kmutil
there cannot see what the newer kernel moved to com.apple.kpi.private (the
very bug: thread_call_cancel_wait on 26). tools/ci/kmutil_kpi_guard.py checks
every import against these lists as well.

    gen_xnu_kpi_lists.py --tag xnu-12377.101.15 [--src DIR] [--out tools/ci/data]

--src: a directory holding the config/*.exports files of that tag (otherwise
they are fetched from github.com/apple-oss-distributions/xnu). Each KPI kext is
built from <Name>.exports + <Name>.x86_64.exports + <Name>.x86_64.MacOSX.exports
(xnu config/Makefile); an entry is a symbol, a 'symbol:alias' / 'symbol : alias'
(the left side is what is exported) or a pattern with '*'.

Output: xnu-<tag>-x86_64-private-only.txt (in Private, in no public KPI and not
in Unsupported) and xnu-<tag>-x86_64-unsupported-only.txt (in Unsupported, in
no public KPI); public = BSDKernel, IOKit, Libkern, MACFramework, Mach.
"""
import fnmatch
import os
import sys
import urllib.request

PUBLIC = ("BSDKernel", "IOKit", "Libkern", "MACFramework", "Mach")
SUFFIXES = ("", ".x86_64", ".x86_64.MacOSX")
URL = "https://raw.githubusercontent.com/apple-oss-distributions/xnu/%s/config/%s"


def read_exports(tag, src, name):
    """the exported names and patterns of one KPI (its three files; a missing one is empty)"""
    out = set()
    for suf in SUFFIXES:
        fn = name + suf + ".exports"
        txt = None
        if src:
            p = os.path.join(src, fn)
            if os.path.exists(p):
                with open(p, errors="replace") as f:
                    txt = f.read()
        else:
            try:
                with urllib.request.urlopen(URL % (tag, fn), timeout=30) as r:
                    txt = r.read().decode("utf-8", "replace")
            except OSError as e:
                if getattr(e, "code", None) != 404:
                    raise SystemExit("gen_xnu_kpi_lists: cannot fetch %s: %s" % (fn, e))
        for line in (txt or "").splitlines():
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            sym = line.split(":", 1)[0].strip()
            if sym:
                out.add(sym)
    return out


def covered(sym, exact, patterns):
    return sym in exact or any(fnmatch.fnmatchcase(sym, p) for p in patterns)


def only(mine, others):
    """the entries of 'mine' no entry of 'others' covers, then '!name' for every exact name of 'others' that a
    kept pattern would match (the guard skips those)"""
    exact = {s for s in others if "*" not in s}
    pats = [s for s in others if "*" in s]
    kept = sorted(s for s in mine if not covered(s, exact, pats))
    kept_pats = [s for s in kept if "*" in s]
    exc = sorted("!" + s for s in exact if any(fnmatch.fnmatchcase(s, p) for p in kept_pats))
    return kept + exc


def main(argv):
    args = dict(zip(argv[0::2], argv[1::2]))
    tag = args.get("--tag")
    if not tag or len(argv) % 2:
        raise SystemExit(__doc__)
    src = args.get("--src")
    out = args.get("--out", os.path.join(os.path.dirname(os.path.abspath(__file__)), "data"))
    public = set()
    for n in PUBLIC:
        public |= read_exports(tag, src, n)
    private = read_exports(tag, src, "Private")
    unsupported = read_exports(tag, src, "Unsupported")
    if not public or not private or not unsupported:
        raise SystemExit("gen_xnu_kpi_lists: an empty KPI (public %d, private %d, unsupported %d): wrong --src?"
                         % (len(public), len(private), len(unsupported)))
    lists = {
        "private-only": (only(private, public | unsupported),
                         "exported only by com.apple.kpi.private: a kext kmutil links cannot import it"),
        "unsupported-only": (only(unsupported, public),
                             "exported by com.apple.kpi.unsupported (maybe also private) and by no public KPI: "
                             "the kext must declare com.apple.kpi.unsupported"),
    }
    os.makedirs(out, exist_ok=True)
    for kind, (syms, what) in lists.items():
        p = os.path.join(out, "%s-x86_64-%s.txt" % (tag, kind))
        with open(p, "w") as f:
            f.write("# %s x86_64: %s\n# generated by tools/ci/gen_xnu_kpi_lists.py --tag %s from config/*.exports "
                    "(public = %s); '*' entries are patterns, '!' entries public exceptions to them\n" % (tag, what, tag, ", ".join(PUBLIC)))
            f.write("\n".join(syms) + "\n")
        print("gen_xnu_kpi_lists: %s: %d symbols" % (p, len(syms)))


if __name__ == "__main__":
    main(sys.argv[1:])
