#!/usr/bin/env python3
"""
gen_regs.py - extract a subset of registers (offset, BASE_IDX, field
SHIFT/MASK, _DEFAULT) from the Linux amdgpu asic_reg headers (MIT, AMD)
into one self-contained header for hw/.

  tools/gen_regs.py --out hw/gen/gc_11_0_3.h --guard GC_11_0_3_H \
      --offset gc_11_0_3_offset.h --mask gc_11_0_3_sh_mask.h \
      --default gc_11_0_3_default.h  regGCVM_L2_CNTL regGCMC_VM_AGP_BASE ...

Register names may be given with or without the 'reg' prefix.
"""
import argparse, re, sys

def defines(path):
    out = {}
    if not path:
        return out
    for line in open(path, errors="replace"):
        m = re.match(r"\s*#define\s+(\w+)\s+(\S+)", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out

ap = argparse.ArgumentParser()
ap.add_argument("--out", required=True)
ap.add_argument("--guard", required=True)
ap.add_argument("--offset", required=True)
ap.add_argument("--mask", required=True)
ap.add_argument("--default")
ap.add_argument("--source", default="")
ap.add_argument("regs", nargs="+")
a = ap.parse_args()

off, msk, dfl = defines(a.offset), defines(a.mask), defines(a.default)
lines = [
    "/*",
    " * GENERATED by tools/gen_regs.py from Linux amdgpu register headers",
    " * (drivers/gpu/drm/amd/include/asic_reg, MIT, Copyright Advanced Micro Devices).",
    f" * Source: {a.source}" if a.source else " *",
    " * Do not edit; regenerate.",
    " *",
    " * SPDX-License-Identifier: MIT",
    " */",
    f"#ifndef {a.guard}",
    f"#define {a.guard}",
    "",
]
missing = []
for r in a.regs:
    reg = r if r.startswith("reg") else "reg" + r
    name = reg[3:]
    if reg not in off:
        missing.append(reg)
        continue
    lines.append(f"/* {name} */")
    lines.append(f"#define {reg:<56} {off[reg]}")
    lines.append(f"#define {reg + '_BASE_IDX':<56} {off.get(reg + '_BASE_IDX', '0')}")
    if reg + "_DEFAULT" in dfl:
        lines.append(f"#define {reg + '_DEFAULT':<56} {dfl[reg + '_DEFAULT']}")
    for k, v in msk.items():
        if k.startswith(name + "__") and (k.endswith("__SHIFT") or k.endswith("_MASK")):
            lines.append(f"#define {k:<56} {v}")
    lines.append("")
lines.append(f"#endif /* {a.guard} */")
open(a.out, "w").write("\n".join(lines) + "\n")
if missing:
    sys.exit("missing registers: " + " ".join(missing))
