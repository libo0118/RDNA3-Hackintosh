ROOT = os.path.dirname(os.path.dirname(HERE))

# Kernel/Add, in load order: Lilu first (the plugins need it), the driver's core kext last.
# (src dir in OUT/src, bundle name, comment)
KEXTS = (
    ("Lilu", "Lilu", "Lilu 1.7.2: patch engine (macOS 26 + AMD CPU support)"),
    ("VirtualSMC", "VirtualSMC", "SMC emulation (no Intel plugins: SMCProcessor is Intel only)"),
    ("RestrictEvents", "RestrictEvents", "About This Mac names the real AMD CPU"),
    ("AppleALC", "AppleALC", "onboard audio (ALC897), layout from the alcid boot-arg"),
    ("RealtekRTL8111", "RealtekRTL8111", "Ethernet RTL8111/8168"),
    ("NVMeFix", "NVMeFix", "NVMe power management (DRAM-less Crucial P3 / P310)"),
)
CORE_KEXT = "RDNA3Accel"
CORE_KERNEL_MIN = "25.0.0"        # Darwin 25 = macOS 26 Tahoe (docs/INSTALL-OPENCORE.md section 3)
CORE_KERNEL_MAX = "25.99.99"

SSDTS = ("SSDT-EC-USBX-DESKTOP.aml", "SSDT-CPUR.aml")
# only what is used: the builtin text picker needs no Resources and no OpenCanopy
DRIVERS = ("OpenRuntime.efi", "OpenHfsPlus.efi", "ResetNvramEntry.efi")

# The boot-args of the card VM's "apps" ladder step (tools/ladder-steps.txt) without what is
# VM-only or a test aid: serial=3 (VM serial port), gemini_check (OSX-KVM), rdna3probe /
# rdna3ladder (report tools). The driver's default profile (common/rdna3_bootargs.h) supplies
# rdna3lvl=8 msi=1 dmub=1 fb=1 mirror=2 accel=1 accelfb=4 acceliop=1 pm=2 idlecap=1 dpms=1 modes=1;
# rdna3agdc=3 is the WindowServer-on-the-plugin switch the profile does not have.
COMMON_ARGS = "-v keepsyms=1 debug=0x100 msgbuf=1048576"
DRIVER_ARGS = "amfi=0x80 rdna3agdc=3"
# csr-active-config of docs/INSTALL-OPENCORE.md section 4 (SIP relaxed for ad-hoc signed kexts)
CSR_ACTIVE_CONFIG = bytes.fromhex("EF0F0000")

GUID_APPLE_BOOT = "7C436110-AB2A-4BBB-A880-FE41995C9F82"
GUID_APPLE_UI = "4D1EDE05-38C7-4A6A-9CC6-4BCCA8B38C14"


class BuildError(Exception):
    pass


def load_vmtool():
    """tools/vm/vmtool.py as a module (the AMD_Vanilla loader and its sha256 check live there)"""
    spec = importlib.util.spec_from_file_location("rdna3_vmtool", os.path.join(ROOT, "tools", "vm", "vmtool.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# ------------------------------------------------------------------ pieces of the config

def amd_kernel_patches(cores, vmtool=None, patch_file=None):
    """AMD_Vanilla's kernel patches as OpenCore Kernel/Patch dicts, the four
    cpuid_cores_per_package ones with the core count in the byte after the opcode (mov eax|edx,
    imm32: B8|BA <count> 00 00 00; AMD_Vanilla README) - the same edit vmtool.py makes for the VM"""
    vmtool = vmtool or load_vmtool()
    if not 1 <= cores <= 255:
        raise BuildError("core count %r is not 1..255" % cores)
    out = []
    for p in vmtool.amd_patches(patch_file):
        p = dict(p)
        if vmtool.AMD_CORES_COMMENT in p.get("Comment", ""):
            rep = bytearray(p["Replace"])
            if len(rep) < 2 or rep[0] not in (0xB8, 0xBA) or rep[1] != 0:
                raise BuildError("AMD_Vanilla core count patch has an unexpected Replace %s" % bytes(rep).hex())
            rep[1] = cores
            p["Replace"] = bytes(rep)
        p["Comment"] = "AMD_Vanilla: %s" % p.get("Comment", "")
        full = {"Arch": "Any", "Base": "", "Comment": "", "Count": 0, "Enabled": True, "Find": b"",
                "Identifier": "kernel", "Limit": 0, "Mask": b"", "MaxKernel": "", "MinKernel": "",
                "Replace": b"", "ReplaceMask": b"", "Skip": 0}
        full.update({k: v for k, v in p.items() if k in full})
        out.append(full)
    if not out:
        raise BuildError("no AMD_Vanilla kernel patches")
    return out


def kext_info(path):
    """(CFBundleIdentifier, CFBundleVersion, executable file name) of a kext folder"""
    with open(os.path.join(path, "Contents", "Info.plist"), "rb") as f:
        info = plistlib.load(f)
    return info.get("CFBundleIdentifier", ""), info.get("CFBundleVersion", ""), info.get("CFBundleExecutable", "")


def kext_entry(name, path, comment, enabled=True, min_kernel="", max_kernel=""):
    """one Kernel/Add dict for the kext folder at PATH (EFI/OC/Kexts/NAME.kext)"""
    bid, ver, exe = kext_info(path)
    if not exe or not os.path.isfile(os.path.join(path, "Contents", "MacOS", exe)):
        raise BuildError("%s has no executable Contents/MacOS/%s" % (path, exe))
    return {"Arch": "Any", "BundlePath": name + ".kext", "Comment": "%s [%s %s]" % (comment, bid, ver),
            "Enabled": enabled, "ExecutablePath": "Contents/MacOS/" + exe, "MaxKernel": max_kernel,
            "MinKernel": min_kernel, "PlistPath": "Contents/Info.plist"}


def parse_efibootmgr(text):
    """[(label, device path)] of the Linux-looking loaders in `efibootmgr -v` output, e.g.
    ('GRUB', 'HD(1,GPT,<guid>,0x800,0x200000)/\\EFI\\GRUB\\GRUBX64.EFI'); Windows, OpenCore and
    firmware entries are not returned (OpenCore finds those itself or the owner does not want them)"""
    found = []
    for line in text.splitlines():
        m = re.match(r"Boot[0-9A-Fa-f]{4}\*?\s+(.*?)\t(HD\([^)]*\)/(?:\\[^\\\t]+?)+?\.efi)", line, re.I)
        if not m:
            continue
        label, path = m.group(1).strip(), m.group(2)
        if re.search(r"windows|opencore|uefi|usb|shell", label, re.I):
            continue
        if re.search(r"microsoft|opencore|\\OC\\", path, re.I):
            continue
        found.append((label, path))
    return found


def make_entries(sample_entry, extra):
    """Misc/Entries for the (name, device path) pairs, built from the Sample's own entry dict
    so every key of this OpenCore release is present"""
    entries = []
    for name, path in extra:
        e = dict(sample_entry)
        e.update({"Name": name, "Path": path, "Enabled": True, "Auxiliary": False, "Arguments": "",
                  "Comment": "Linux loader on the shared EFI partition (from efibootmgr)", "Flavour": "Linux:Auto"})
        entries.append(e)
    return entries


def driver_entry(path):
    return {"Arguments": "", "Comment": "", "Enabled": True, "HideVerbose": False, "LoadEarly": False, "Path": path}


def boot_args(stage, alcid):
    args = "%s alcid=%d" % (COMMON_ARGS, alcid)
    if stage == "driver":
        args += " " + DRIVER_ARGS
    return args


def build_config(sample, stage, *, kexts, cores, smbios, identity, alcid, entries=(), vmtool=None,
                 patch_file=None, timeout=None, resize_bars=10):
    """the config.plist dict for STAGE ('installer' or 'driver') from the Sample.plist dict.
    KEXTS = [(Kernel/Add dict)] already in load order (the core kext last, enabled or not as
    its dict says). Nothing in SAMPLE is modified."""
    if stage not in ("installer", "driver"):
        raise BuildError("stage must be installer or driver")
    c = copy.deepcopy(sample)

    # ACPI: the two prebuilt Dortania SSDTs (a fake EC for macOS and USBX power, and the
    # B550/A520 Zen 3 CPU naming: \_SB.PLTF.C000.. -> PR00..)
    c["ACPI"]["Add"] = [{"Comment": "Dortania: fake EC + USBX power (this board has no PNP0C09 EC)",
                         "Enabled": True, "Path": SSDTS[0]},
                        {"Comment": "Dortania: B550/A520 Zen 3 CPU names (\\_SB.PLTF.C000 -> PR00)",
                         "Enabled": True, "Path": SSDTS[1]}]

    # Booter: Dortania "Ryzen and Threadripper"; ResizeAppleGpuBars 10 = BAR0 cut to 1 GiB for
    # macOS only, the most it takes (docs/INSTALL-OPENCORE.md section 5, DRIVER-PLAN N62)
    c["Booter"]["Quirks"].update({
        "AvoidRuntimeDefrag": True, "DevirtualiseMmio": False, "EnableSafeModeSlide": True,
        "EnableWriteUnprotector": False, "ProvideCustomSlide": True, "RebuildAppleMemoryMap": True,
        "ResizeAppleGpuBars": resize_bars, "SetupVirtualMap": True, "SyncRuntimePermissions": True})

    # Kernel
    c["Kernel"]["Add"] = list(kexts)
    c["Kernel"]["Patch"] = amd_kernel_patches(cores, vmtool, patch_file)
    c["Kernel"]["Emulate"].update({"Cpuid1Data": b"", "Cpuid1Mask": b"", "DummyPowerManagement": True,
                                   "MinKernel": "", "MaxKernel": ""})
    c["Kernel"]["Quirks"].update({
        "AppleCpuPmCfgLock": False, "AppleXcpmCfgLock": False, "DisableIoMapper": True,
        "DisableLinkeditJettison": True, "PanicNoKextDump": True, "PowerTimeoutKernelPanic": True,
        "ProvideCurrentCpuInfo": True, "XhciPortLimit": False})

    # Misc: a visible picker for dual boot; Linux's GRUB as an entry; SIP/Secure Boot model as the VM
    boot = c["Misc"]["Boot"]
    boot.update({"ShowPicker": True, "PickerMode": "Builtin", "HideAuxiliary": False,   # the recovery (com.apple.recovery.boot dmg) is an auxiliary entry: hidden, the picker offered only the stick itself (2026-10-29)
                 "LauncherOption": "Disabled",
                 "Timeout": 0 if timeout is None else timeout})
    c["Misc"]["Security"].update({"ScanPolicy": 0, "SecureBootModel": "Disabled", "Vault": "Optional",
                                  "AllowSetDefault": True, "DmgLoading": "Signed",
                                  "BlacklistAppleUpdate": True})
    c["Misc"]["Entries"] = make_entries(sample["Misc"]["Entries"][0], entries)
    c["Misc"]["Tools"] = []

    # NVRAM
    boot_nv = c["NVRAM"]["Add"][GUID_APPLE_BOOT]
    boot_nv.update({"boot-args": boot_args(stage, alcid), "csr-active-config": CSR_ACTIVE_CONFIG,
                    "prev-lang:kbd": b"en-US:0", "run-efi-updater": "No"})
    boot_nv.pop("ForceDisplayRotationInEFI", None)
    boot_nv.pop("SystemAudioVolume", None)
    boot_nv.pop("#INFO (prev-lang:kbd)", None)
    c["NVRAM"]["Add"][GUID_APPLE_BOOT] = boot_nv
    c["NVRAM"]["Delete"][GUID_APPLE_BOOT] = ["boot-args", "csr-active-config"]
    c["NVRAM"]["WriteFlash"] = True

    # PlatformInfo: MacPro7,1 (the card VM's play-desktop model), generated serials
    g = c["PlatformInfo"]["Generic"]
    g.update({"SystemProductName": smbios, "SystemSerialNumber": identity["serial"], "MLB": identity["mlb"],
              "SystemUUID": identity["uuid"], "ROM": bytes.fromhex(identity["rom"]), "SpoofVendor": True})
    c["PlatformInfo"]["Automatic"] = True

    # UEFI
    c["UEFI"]["Drivers"] = [driver_entry(d) for d in DRIVERS]
    c["UEFI"]["Output"].update({"Resolution": "Max", "ProvideConsoleGop": True})
    c["UEFI"]["Quirks"].update({"ReleaseUsbOwnership": True, "RequestBootVarRouting": True,
                                "ResizeGpuBars": -1})
    c["UEFI"]["ConnectDrivers"] = True
    c["UEFI"]["APFS"].update({"EnableJumpstart": True, "MinDate": 0, "MinVersion": 0})

    # driver stage: nothing else differs from the installer's file but the kext switch and the
    # boot-args above; the picker may time out because nobody waits at an installer
    if stage == "driver":
        for k in c["Kernel"]["Add"]:
            if k["BundlePath"] == CORE_KEXT + ".kext":
                k["Enabled"] = True
        if timeout is None:
            boot["Timeout"] = 10
    return c


