def find_kext(root, bundle):
    """the first NAME.kext folder under ROOT that is not a dSYM or in __MACOSX"""
    for d, dirs, _ in os.walk(root):
        dirs[:] = [x for x in dirs if x != "__MACOSX" and not x.endswith(".dSYM")]
        if bundle + ".kext" in dirs:
            return os.path.join(d, bundle + ".kext")
    raise BuildError("no %s.kext under %s (run tools/baremetal/fetch.sh)" % (bundle, root))


def copy_kext(src, dst_dir, name):
    dst = os.path.join(dst_dir, name + ".kext")
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns(".DS_Store", "*.dSYM", "._*"))
    return dst


def extract_core_kext(zip_path, dest):
    """RDNA3Accel.kext out of the CI kext artifact (members checked: no absolute paths or ..)"""
    prefix = CORE_KEXT + ".kext/"
    n = 0
    with zipfile.ZipFile(zip_path) as z:
        for m in z.infolist():
            if not m.filename.startswith(prefix):
                continue
            norm = os.path.normpath(m.filename)
            if os.path.isabs(norm) or norm.startswith(".."):
                raise BuildError("unsafe path in %s: %s" % (zip_path, m.filename))
            target = os.path.join(dest, norm)
            if m.is_dir():
                os.makedirs(target, exist_ok=True)
                continue
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with z.open(m) as src, open(target, "wb") as out:
                shutil.copyfileobj(src, out)
            os.chmod(target, 0o755 if m.filename.split("/")[-2] == "MacOS" else 0o644)
            n += 1
    if n == 0:
        raise BuildError("%s has no %s" % (zip_path, prefix))
    return os.path.join(dest, CORE_KEXT + ".kext")


def make_identity(path, macserial, smbios):
    """OUT/identity.json: serial, MLB, UUID and ROM, generated once (macserial for the first two)
    and then reused so that rebuilding the EFI does not change the Mac's identity"""
    if os.path.isfile(path):
        with open(path) as f:
            ident = json.load(f)
        if ident.get("smbios") == smbios and all(ident.get(k) for k in ("serial", "mlb", "uuid", "rom")):
            return ident
    r = subprocess.run([macserial, "-m", smbios, "-n", "1"], capture_output=True, text=True, check=False)
    line = [ln for ln in r.stdout.splitlines() if "|" in ln]
    if r.returncode != 0 or not line:
        raise BuildError("macserial -m %s failed: %s" % (smbios, (r.stdout + r.stderr).strip()))
    serial, mlb = [x.strip() for x in line[0].split("|")]
    if not re.fullmatch(r"[A-Z0-9]{11,12}", serial) or not re.fullmatch(r"[A-Z0-9]{17}", mlb):
        raise BuildError("macserial gave an odd serial / MLB: %r %r" % (serial, mlb))
    rom = bytearray(secrets.token_bytes(6))
    rom[0] &= 0xFE                 # unicast
    ident = {"smbios": smbios, "serial": serial, "mlb": mlb, "uuid": str(uuid.uuid4()).upper(), "rom": rom.hex()}
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump(ident, f, indent=1)
    return ident


def detect_cores():
    """physical cores of this machine (the AMD_Vanilla core count), 0 when unknown"""
    try:
        with open("/proc/cpuinfo") as f:
            m = re.search(r"^cpu cores\s*:\s*(\d+)", f.read(), re.M)
        return int(m.group(1)) if m else 0
    except OSError:
        return 0


def ocvalidate_issues(text):
    """the issue lines of ocvalidate's output (not its banner, summary or per-section counts)"""
    return [ln.strip() for ln in text.splitlines()
            if ln.strip() and not ln.startswith("NOTE:") and not ln.startswith("Completed validating")
            and not re.match(r"Check\w+ returns \d+ error", ln.strip())]


def run_ocvalidate(tool, config, allow_bar_note=False):
    """(ok, text). ocvalidate calls every ResizeAppleGpuBars of 0 or more a problem (8: "not
    useful for macOS", above 8: "unstable with macOS sleep-wake"); that is the one note
    allow_bar_note accepts: 10 (1 GiB, the most macOS takes) is the choice of
    docs/INSTALL-OPENCORE.md section 5 (DRIVER-PLAN N62) and the driver does not sleep yet"""
    r = subprocess.run([tool, config], capture_output=True, text=True, check=False)
    text = (r.stdout + r.stderr).strip()
    if r.returncode == 0:
        return True, text
    issues = ocvalidate_issues(text)
    if allow_bar_note and issues and all("ResizeAppleGpuBars" in i for i in issues):
        return True, text
    return False, text


def build(args):
    out = os.path.abspath(os.path.expanduser(args.out))
    oc_src = os.path.join(out, "src", "OpenCorePkg")
    sample_path = os.path.join(oc_src, "Docs", "Sample.plist")
    for p in (sample_path, os.path.join(oc_src, "X64", "EFI", "OC", "OpenCore.efi")):
        if not os.path.isfile(p):
            raise BuildError("%s is missing: run tools/baremetal/fetch.sh %s" % (p, out))
    with open(sample_path, "rb") as f:
        sample = plistlib.load(f)

    efi = os.path.join(out, "efi")
    if os.path.isdir(efi):
        shutil.rmtree(efi)
    oc = os.path.join(efi, "EFI", "OC")
    for d in ("ACPI", "Drivers", "Kexts", os.path.join("..", "BOOT")):
        os.makedirs(os.path.join(oc, d))
    shutil.copy(os.path.join(oc_src, "X64", "EFI", "BOOT", "BOOTx64.efi"), os.path.join(efi, "EFI", "BOOT"))
    shutil.copy(os.path.join(oc_src, "X64", "EFI", "OC", "OpenCore.efi"), oc)
    for d in DRIVERS:
        shutil.copy(os.path.join(oc_src, "X64", "EFI", "OC", "Drivers", d), os.path.join(oc, "Drivers"))
    for a in SSDTS:
        src = os.path.join(out, "dl", a)
        if not os.path.isfile(src):
            raise BuildError("%s is missing: run tools/baremetal/fetch.sh" % src)
        shutil.copy(src, os.path.join(oc, "ACPI"))

    kexts = []
    for src_dir, bundle, comment in KEXTS:
        path = copy_kext(find_kext(os.path.join(out, "src", src_dir), bundle), os.path.join(oc, "Kexts"), bundle)
        kexts.append(kext_entry(bundle, path, comment))
    if args.kext_dir:
        core_src = os.path.join(os.path.expanduser(args.kext_dir), CORE_KEXT + ".kext")
    else:
        zp = os.path.expanduser(args.kext_zip)
        if not os.path.isfile(zp):
            raise BuildError("%s not found: download the CI artifact RDNA3Accel-kext (build.yml, job kext) "
                             "or pass --kext-zip / --kext-dir" % zp)
        tmp = os.path.join(out, "core-kext")
        if os.path.isdir(tmp):
            shutil.rmtree(tmp)
        os.makedirs(tmp)
        core_src = extract_core_kext(zp, tmp)
    core = copy_kext(core_src, os.path.join(oc, "Kexts"), CORE_KEXT)
    kexts.append(kext_entry(CORE_KEXT, core, "RDNA3-Hackintosh core kext (docs/INSTALL-OPENCORE.md)",
                            enabled=False, min_kernel=CORE_KERNEL_MIN, max_kernel=CORE_KERNEL_MAX))

    cores = args.cores or detect_cores()
    if not cores:
        raise BuildError("cannot detect the physical core count: pass --cores")
    ident = make_identity(os.path.join(out, "identity.json"),
                          os.path.join(oc_src, "Utilities", "macserial", "macserial.linux"), args.smbios)

    entries = []
    for e in args.entry or []:
        name, _, path = e.partition("=")
        if not name or not path:
            raise BuildError("--entry wants NAME=DEVICEPATH, got %r" % e)
        entries.append((name, path))
    if args.detect_linux:
        r = subprocess.run(["efibootmgr", "-v"], capture_output=True, text=True, check=False)
        entries += parse_efibootmgr(r.stdout)

    vm = load_vmtool()
    problems = 0
    for stage, name in (("installer", "config-installer.plist"), ("driver", "config-driver.plist")):
        cfg = build_config(sample, stage, kexts=[dict(k) for k in kexts], cores=cores, smbios=args.smbios,
                           identity=ident, alcid=args.alcid, entries=entries, vmtool=vm,
                           resize_bars=args.resize_bars)
        path = os.path.join(oc, name)
        with open(path, "wb") as f:
            plistlib.dump(cfg, f)
        if stage == "installer":
            shutil.copy(path, os.path.join(oc, "config.plist"))
    if not args.no_validate:
        tool = os.path.join(oc_src, "Utilities", "ocvalidate", "ocvalidate.linux")
        for name in ("config.plist", "config-driver.plist"):
            ok, text = run_ocvalidate(tool, os.path.join(oc, name), allow_bar_note=args.resize_bars >= 0)
            note = " (only its ResizeAppleGpuBars=%d note)" % args.resize_bars if ok and "issue" in text else ""
            print("ocvalidate %s: %s%s" % (name, "OK" if ok else "FAILED", note))
            if not ok:
                print(text)
                problems += 1
    print("EFI written to %s (cores %d, SMBIOS %s, alcid %d, %d Linux entries)"
          % (efi, cores, args.smbios, args.alcid, len(entries)))
    for n in ("EFI/BOOT/BOOTx64.efi", "EFI/OC/OpenCore.efi"):
        print("  " + n)
    for k in kexts:
        print("  EFI/OC/Kexts/%s  %s" % (k["BundlePath"], "(disabled in the installer config)" if not k["Enabled"] else ""))
    return 1 if problems else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default="~/rdna3-baremetal", help="the fetch.sh output directory")
    ap.add_argument("--kext-zip", default="~/Downloads/RDNA3Accel-kext.zip",
                    help="CI artifact 'RDNA3Accel-kext' (build.yml, job kext)")
    ap.add_argument("--kext-dir", help="a folder holding RDNA3Accel.kext instead of the zip")
    ap.add_argument("--cores", type=int, default=0, help="physical cores (default: this machine's, 8 on a 5800X)")
    ap.add_argument("--smbios", default="MacPro7,1")
    ap.add_argument("--alcid", type=int, default=13,
                    help="AppleALC layout-id for the ALC897 (13 = MSI Z590-A PRO; try 69, 31 if silent)")
    ap.add_argument("--resize-bars", type=int, default=10,
                    help="Booter ResizeAppleGpuBars: 10 = BAR0 cut to 1 GiB for macOS, 8 = 256 MiB (VM-proven), "
                         "-1 = off (Resizable BAR off in the BIOS)")
    ap.add_argument("--entry", action="append", metavar="NAME=DEVICEPATH",
                    help="extra picker entry, e.g. 'Linux=HD(1,GPT,<guid>,0x800,0x200000)/\\EFI\\GRUB\\GRUBX64.EFI'")
    ap.add_argument("--detect-linux", action="store_true",
                    help="add the Linux loaders efibootmgr -v lists (GRUB...) as picker entries")
    ap.add_argument("--no-validate", action="store_true", help="skip ocvalidate")
    args = ap.parse_args(argv)
    try:
        return build(args)
    except BuildError as e:
        print("build_efi.py: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
