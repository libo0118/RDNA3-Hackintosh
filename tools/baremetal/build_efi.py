#!/usr/bin/env python3
"""build_efi.py - the OpenCore EFI folder for the owner's real PC (Ryzen 7 5800X, MSI B550-A PRO).

    python3 -I tools/baremetal/build_efi.py --out ~/rdna3-baremetal

Reads what tools/baremetal/fetch.sh left in OUT (src/, dl/) and writes OUT/efi/EFI/{BOOT,OC}:

  EFI/OC/config.plist            the INSTALLER configuration (same as config-installer.plist):
                                 our RDNA3Accel.kext is in Kernel/Add but disabled, no rdna3
                                 boot-args: the installer runs on the card's GOP framebuffer
  EFI/OC/config-installer.plist  the same file under its own name
  EFI/OC/config-driver.plist     the same with the kext enabled and the driver's boot-args;
                                 copy it over config.plist once macOS is installed (docs/BAREMETAL.md)

Both start from OpenCore's own Docs/Sample.plist (so every key of this OpenCore release is there)
and change what the Dortania AMD (Zen) guide changes. SMBIOS serials are generated by OpenCore's
macserial and kept in OUT/identity.json, never in git. Both configs are checked with ocvalidate.

The AMD_Vanilla kernel patches and their core-count byte are the ones the card VM runs
(tools/vm/vmtool.py amd_patches, tools/vm/data/amd_vanilla.SOURCE); the Lilu / RestrictEvents
pins are the VM's too (tools/vm/data/oc_kexts.SOURCE).
"""
